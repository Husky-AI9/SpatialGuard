// Builds the web home map (2D, 3D, controls, heatmap) and packs it into
// src/mapEmbedHtml.ts for the native WebView. Run after changing the web map:
//   node scripts/build-map-embed.mjs
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "../../web");
execSync("npx vite build -c vite.embed.config.ts", { cwd: web, stdio: "inherit" });
const script = readFileSync(resolve(web, "dist-embed/map.js"), "utf8").replace(/<\/script/gi, "<\/script");
const style = readFileSync(resolve(web, "dist-embed/map.css"), "utf8").replace(/<\/style/gi, "<\/style");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; font-src data:">
<style>${style}</style></head><body><div id="root"></div><script>${script}</script></body></html>`;
writeFileSync(
  resolve(here, "../src/mapEmbedHtml.ts"),
  "// Generated by scripts/build-map-embed.mjs from apps/web/src/embed. Do not edit.\n" +
    `export default ${JSON.stringify(html)};\n`,
);
console.log(`mapEmbedHtml.ts: ${(html.length / 1024).toFixed(0)} KB`);
